def repo_head(repo: Path) -> str:
    """Return `git rev-parse HEAD` for *repo* (read-only query)."""
    result = subprocess.run(
        ["git", "rev-parse", "HEAD"],
        cwd=repo,
        capture_output=True,
        text=True,
        check=True,
    )
    return result.stdout.strip()


def _row(values: tuple[str, str]) -> str:
    return "(" + ", ".join(values) + ")"


def _slice(values: tuple[tuple[str, str], tuple[str, str]]) -> str:
    return "( " + ", ".join(_row(r) for r in values) + " )"


