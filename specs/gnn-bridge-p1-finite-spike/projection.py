def write_document() -> int:
    """Regenerate the artifact in place (default mode)."""
    document = build_document(repo_head(FEP_LEAN_ROOT), repo_head(GNN_ROOT))
    ARTIFACT_PATH.parent.mkdir(parents=True, exist_ok=True)
    ARTIFACT_PATH.write_text(document, encoding="utf-8")
    print(f"wrote {ARTIFACT_PATH} ({len(document)} bytes)")
    return 0


def check_document() -> int:
    """Freshness gate: regenerated bytes and live digests must match."""
    fep_lean_head = repo_head(FEP_LEAN_ROOT)
    gnn_head = repo_head(GNN_ROOT)
    regenerated = build_document(fep_lean_head, gnn_head)
    if not ARTIFACT_PATH.is_file():
        print(f"DRIFT: missing artifact {ARTIFACT_PATH}")
        return 1
    on_disk = ARTIFACT_PATH.read_text(encoding="utf-8")
    if on_disk != regenerated:
        print(
            "DRIFT: on-disk document differs from regeneration at"
            f" fep_lean {fep_lean_head} / GNN {gnn_head}"
        )
        return 1
    print(
        "FRESH:"
        f" fep_lean {fep_lean_head} / GNN {gnn_head}"
        " — regenerated bytes match on-disk artifact"
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Deterministic fep_lean -> GNN projector for the bridge P1"
            " finite spike; --check gates freshness."
        )
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero when the artifact is missing or stale",
    )
    args = parser.parse_args(argv)
    if args.check:
        return check_document()
    return write_document()


if __name__ == "__main__":
    sys.exit(main())
