def write_document() -> int:
    """Emit from the explicit W2 source pin (never implicitly move HEAD)."""
    from fep_lean.bridge.operations import emit

    emit(FEP_LEAN_ROOT, GNN_ROOT, "continuous")
    return 0


def check_document() -> int:
    """Read-only check of pinned owners and artifact bytes."""
    from fep_lean.bridge.operations import emit

    return 0 if emit(FEP_LEAN_ROOT, GNN_ROOT, "continuous", check=True) else 1


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Deterministic fep_lean -> GNN projector for the bridge P4b"
            " continuous emission; --check gates freshness."
        )
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero when the artifact is missing or stale",
    )
    args = parser.parse_args(argv)
    if args.check:
        return check_document()
    return write_document()


if __name__ == "__main__":
    sys.exit(main())
