def repo_head(repo: str) -> str:
    """Return `git rev-parse HEAD` for *repo* (read-only query)."""
    result = subprocess.run(
        ["git", "rev-parse", "HEAD"],
        cwd=repo,
        capture_output=True,
        text=True,
        check=True,
    )
    return result.stdout.strip()


